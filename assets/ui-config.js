/*
 * UI（見た目）設定
 * ------------------------------------------------------------
 * タイトルのキャラ選択ボタンの顔の切り抜き、タイトルロゴ画像・背景画像の差し込み口をまとめています。
 * 画像のパスは index.html からの相対パスです。null（または画像が無い・読み込めない）のときは、今までどおりの表示になります。
 */
window.UI_CONFIG = {
  // ---- タイトルロゴ ----
  // 例：'assets/ui/logo.png'。設定すると、タイトルの文字の代わりにこの画像を表示します。
  titleLogo: {
    src: null,
    maxWidth: 620,   // 表示する最大の幅（px, 960x540 基準）
    maxHeight: 150   // 表示する最大の高さ（px）。大きくしすぎるとボタンがはみ出すので注意
  },

  // ---- 背景 ----
  // far   : 遠景（空など）。画面全体（960x540）に、縦横比を保ったまま隙間なく敷きます。
  // floor : 床。floorRect の範囲に引き伸ばして重ねます（透過 PNG なら遠景の上に重なります）。
  // どちらも null のときは、今までどおりの描画（グラデーションの空と床）になります。
  background: {
    far: null,       // 例：'assets/ui/bg_far.png'
    floor: null,     // 例：'assets/ui/bg_floor.png'
    floorRect: { x: 0, y: 270, w: 960, h: 270 }
  },

  // ---- キャラ選択ボタンの顔 ----
  // 立ちパーツの頭の画像（parts.head.src）から、正方形を切り抜いて丸い枠に表示します。
  //  x, y : 切り抜く正方形の「中心」（頭の画像のピクセル座標）
  //  size : 切り抜く正方形の一辺（ピクセル）。小さくするほど顔が大きく（ズーム）なります。
  //  src  : 別の画像を使いたいとき（省略すると parts.head.src）
  // faceCrop を 'auto' にすると、画像の透明でない範囲から自動で切り抜きます。
  faceCrop: {
    angel:   { x: 143, y: 88,  size: 132 },
    lucifer: { x: 175, y: 104, size: 150 }
  }
};
